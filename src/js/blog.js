document.addEventListener('DOMContentLoaded', () => {
  function getPathPrefix() {
    const path = window.location.pathname;
    if (path.includes('/public/pages/') || path.includes('/public/auth/')) {
      return '../../';
    }
    return './';
  }
  const prefix = getPathPrefix();

  const blogGrid = document.getElementById('blogGrid');
  const searchInput = document.getElementById('blogSearch');
  const filterBtns = document.querySelectorAll('.filter-btn');

  if (blogGrid) {
    let activeCategory = 'All';
    let searchQuery = '';

    function renderFilteredPosts() {
      const filtered = BLOG_POSTS.filter(post => {
        const matchesCategory = activeCategory === 'All' || post.category.toLowerCase() === activeCategory.toLowerCase() || (activeCategory.toLowerCase() === 'diy guides' && post.category.toLowerCase() === 'diy guides');
        const matchesSearch = post.title.toLowerCase().includes(searchQuery.toLowerCase()) || 
                              post.excerpt.toLowerCase().includes(searchQuery.toLowerCase()) ||
                              post.category.toLowerCase().includes(searchQuery.toLowerCase());
        return matchesCategory && matchesSearch;
      });

      if (filtered.length === 0) {
        blogGrid.innerHTML = `
          <div style="grid-column:1/-1;text-align:center;padding:60px 20px">
            <div style="font-size:24px;font-weight:700;margin-bottom:8px">No guides found</div>
            <p style="color:var(--gray-text);font-size:14px">Try adjusting your filters or search query.</p>
          </div>
        `;
        return;
      }

      blogGrid.innerHTML = filtered.map(post => createBlogCardHTML(post, prefix)).join('');
    }

    if (searchInput) {
      searchInput.addEventListener('input', (e) => {
        searchQuery = e.target.value.trim();
        renderFilteredPosts();
      });
    }

    filterBtns.forEach(btn => {
      btn.addEventListener('click', () => {
        filterBtns.forEach(b => {
          b.classList.remove('bg-[var(--red)]', 'text-white');
          b.classList.add('bg-[var(--white)]', 'text-[var(--ink)]');
        });
        btn.classList.remove('bg-[var(--white)]', 'text-[var(--ink)]');
        btn.classList.add('bg-[var(--red)]', 'text-white');
        activeCategory = btn.getAttribute('data-category');
        renderFilteredPosts();
      });
    });

    renderFilteredPosts();
  }

  const detailTitle = document.getElementById('detailTitle');
  const detailMeta = document.getElementById('detailMeta');
  const detailCover = document.getElementById('detailCover');
  const detailBody = document.getElementById('detailBody');
  const authorBox = document.getElementById('authorBox');
  const recentSidebar = document.getElementById('recentSidebar');

  if (detailBody) {
    const params = new URLSearchParams(window.location.search);
    const postId = params.get('id');

    const post = BLOG_POSTS.find(p => p.id === postId);

    if (post) {
      document.title = `${post.title} — Plumpin`;
      if (detailTitle) detailTitle.textContent = post.title;
      if (detailMeta) {
        detailMeta.innerHTML = `
          <span class="hero-badge-pill" style="margin:0"><i class="fas fa-tag"></i> ${post.category}</span>
          <span><i class="far fa-calendar-alt"></i> ${post.date}</span>
          <span><i class="far fa-clock"></i> ${post.readTime}</span>
        `;
      }
      if (detailCover) {
        detailCover.src = post.coverImg;
        detailCover.alt = post.title;
      }
      detailBody.innerHTML = post.content;

      if (authorBox) {
        authorBox.innerHTML = `
          <div style="display:flex;align-items:center;gap:16px">
            <div style="width:48px;height:48px;border-radius:50%;background:var(--red-light);color:var(--red);display:flex;align-items:center;justify-content:center;font-weight:700;font-size:20px;flex-shrink:0">${post.author.charAt(0)}</div>
            <div>
              <div style="font-weight:700;font-size:14px">${post.author}</div>
              <div style="font-size:12px;color:var(--gray-text)">${post.authorTitle}</div>
            </div>
          </div>
        `;
      }
    } else {
      if (detailTitle) detailTitle.textContent = "Guide Not Found";
      if (detailCover) {
        detailCover.style.display = "none";
      }
      detailBody.innerHTML = `
        <div style="text-align:center;padding:60px 20px">
          <div style="font-size:48px;font-weight:700;color:var(--red);margin-bottom:12px">404</div>
          <p style="color:var(--gray-text);margin-bottom:24px">We couldn't locate this specific plumbing manual.</p>
          <a href="${prefix}public/pages/blog.html" class="btn-primary" style="display:inline-flex">Browse All Manuals</a>
        </div>
      `;
    }

    if (recentSidebar) {
      const remainingPosts = BLOG_POSTS.filter(p => p.id !== postId).slice(0, 3);
      recentSidebar.innerHTML = remainingPosts.map(p => `
        <div style="background:var(--white);border-radius:var(--radius-new);box-shadow:var(--shadow);padding:16px;display:flex;flex-direction:column;gap:8px">
          <div style="font-size:11px;color:var(--gray-text);font-family:'IBM Plex Mono',monospace">${p.category} • ${p.readTime}</div>
          <a href="${prefix}public/pages/blog-details.html?id=${p.id}" style="font-weight:700;font-size:14px;line-height:1.3;color:inherit">${p.title}</a>
          <a href="${prefix}public/pages/blog-details.html?id=${p.id}" style="font-size:12px;font-weight:600;color:var(--red)">Read Guide →</a>
        </div>
      `).join('');
    }
  }
});
